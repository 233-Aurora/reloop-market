create table users (
    id bigint generated by default as identity primary key,
    username varchar(32) not null unique,
    email varchar(254) not null unique,
    password_hash varchar(255) not null,
    display_name varchar(64) not null,
    phone varchar(32),
    campus varchar(128),
    avatar_url varchar(512),
    role varchar(16) not null default 'USER',
    status varchar(16) not null default 'ACTIVE',
    reputation_score numeric(3, 2) not null default 5.00,
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    constraint ck_users_role check (role in ('USER', 'ADMIN')),
    constraint ck_users_status check (status in ('ACTIVE', 'SUSPENDED')),
    constraint ck_users_reputation check (reputation_score between 0 and 5)
);

create table item_categories (
    id bigint generated by default as identity primary key,
    name varchar(64) not null,
    parent_id bigint references item_categories (id) on delete restrict,
    sort_order integer not null default 0,
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    constraint uq_item_categories_parent_name unique nulls not distinct (parent_id, name)
);

create table items (
    id bigint generated by default as identity primary key,
    seller_id bigint not null references users (id) on delete restrict,
    category_id bigint references item_categories (id) on delete set null,
    title varchar(120) not null,
    description text not null,
    price numeric(12, 2) not null,
    condition varchar(16) not null,
    status varchar(16) not null default 'ON_SALE',
    location_text varchar(255),
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    constraint ck_items_price check (price >= 0),
    constraint ck_items_condition check (condition in ('NEW', 'LIKE_NEW', 'GOOD', 'FAIR')),
    constraint ck_items_status check (status in ('DRAFT', 'ON_SALE', 'RESERVED', 'SOLD', 'OFF_SHELF'))
);

create index idx_items_status_created_at on items (status, created_at desc);
create index idx_items_category_id on items (category_id);
create index idx_items_seller_id on items (seller_id);

create table item_images (
    id bigint generated by default as identity primary key,
    item_id bigint not null references items (id) on delete cascade,
    storage_key varchar(512) not null unique,
    sort_order integer not null default 0,
    is_primary boolean not null default false,
    created_at timestamptz not null default current_timestamp
);

create unique index uq_item_images_primary on item_images (item_id) where is_primary;
create index idx_item_images_item_id_sort_order on item_images (item_id, sort_order);

create table trade_requests (
    id bigint generated by default as identity primary key,
    item_id bigint not null references items (id) on delete restrict,
    requester_id bigint not null references users (id) on delete restrict,
    seller_id bigint not null references users (id) on delete restrict,
    message varchar(500),
    status varchar(16) not null default 'PENDING',
    requester_confirmed_at timestamptz,
    seller_confirmed_at timestamptz,
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    constraint ck_trade_requests_status check (status in ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED', 'COMPLETED')),
    constraint ck_trade_requests_participants check (requester_id <> seller_id)
);

create index idx_trade_requests_item_status on trade_requests (item_id, status);
create index idx_trade_requests_requester_status on trade_requests (requester_id, status);
create index idx_trade_requests_seller_status on trade_requests (seller_id, status);

create table reviews (
    id bigint generated by default as identity primary key,
    trade_request_id bigint not null references trade_requests (id) on delete restrict,
    reviewer_id bigint not null references users (id) on delete restrict,
    reviewee_id bigint not null references users (id) on delete restrict,
    rating smallint not null,
    comment varchar(1000),
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    constraint uq_reviews_trade_request_reviewer unique (trade_request_id, reviewer_id),
    constraint ck_reviews_rating check (rating between 1 and 5),
    constraint ck_reviews_participants check (reviewer_id <> reviewee_id)
);

create index idx_reviews_reviewee_id_created_at on reviews (reviewee_id, created_at desc);

create table messages (
    id bigint generated by default as identity primary key,
    recipient_id bigint not null references users (id) on delete restrict,
    sender_id bigint references users (id) on delete set null,
    trade_request_id bigint references trade_requests (id) on delete set null,
    message_type varchar(32) not null,
    content varchar(2000) not null,
    is_read boolean not null default false,
    created_at timestamptz not null default current_timestamp,
    constraint ck_messages_sender_recipient check (sender_id is null or sender_id <> recipient_id)
);

create index idx_messages_recipient_read_created_at on messages (recipient_id, is_read, created_at desc);
