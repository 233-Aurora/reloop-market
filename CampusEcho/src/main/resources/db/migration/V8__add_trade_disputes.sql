alter table trade_requests
    drop constraint ck_trade_requests_status;

alter table trade_requests
    add constraint ck_trade_requests_status check (
        status in ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED', 'COMPLETED', 'DISPUTED')
    );

create table trade_disputes (
    id bigint generated by default as identity primary key,
    trade_request_id bigint not null references trade_requests (id) on delete restrict,
    item_id bigint not null references items (id) on delete restrict,
    opener_id bigint not null references users (id) on delete restrict,
    respondent_id bigint not null references users (id) on delete restrict,
    reason varchar(32) not null,
    description varchar(1000) not null,
    status varchar(16) not null default 'OPEN',
    resolution varchar(32),
    resolution_note varchar(1000),
    handled_by bigint references users (id) on delete set null,
    handled_at timestamptz,
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    version bigint not null default 0,
    constraint ck_trade_disputes_reason check (reason in (
        'NON_DELIVERY',
        'ITEM_NOT_AS_DESCRIBED',
        'PAYMENT_ISSUE',
        'NO_SHOW',
        'OTHER'
    )),
    constraint ck_trade_disputes_status check (status in ('OPEN', 'RESOLVED', 'REJECTED')),
    constraint ck_trade_disputes_resolution check (resolution is null or resolution in (
        'COMPLETE_TRADE',
        'CANCEL_TRADE',
        'NONE'
    )),
    constraint ck_trade_disputes_participants check (opener_id <> respondent_id),
    constraint ck_trade_disputes_handling check (
        (status = 'OPEN'
            and resolution is null
            and resolution_note is null
            and handled_by is null
            and handled_at is null)
        or
        (status = 'RESOLVED'
            and resolution in ('COMPLETE_TRADE', 'CANCEL_TRADE')
            and resolution_note is not null
            and handled_by is not null
            and handled_at is not null)
        or
        (status = 'REJECTED'
            and resolution = 'NONE'
            and resolution_note is not null
            and handled_by is not null
            and handled_at is not null)
    )
);

create unique index uq_trade_disputes_open_trade
    on trade_disputes (trade_request_id)
    where status = 'OPEN';

create index idx_trade_disputes_opener_created_at
    on trade_disputes (opener_id, created_at desc);

create index idx_trade_disputes_respondent_created_at
    on trade_disputes (respondent_id, created_at desc);

create index idx_trade_disputes_admin_queue
    on trade_disputes (status, created_at desc);

alter table messages
    add column dispute_id bigint references trade_disputes (id) on delete set null;

alter table messages
    drop constraint ck_messages_message_type;

alter table messages
    add constraint ck_messages_message_type check (
        message_type in (
            'TRADE_REQUEST_CREATED',
            'TRADE_REQUEST_ACCEPTED',
            'TRADE_REQUEST_REJECTED',
            'TRADE_REQUEST_CANCELLED',
            'TRADE_CONFIRMATION_RECEIVED',
            'TRADE_COMPLETED',
            'TRADE_CANCELLED_BY_MODERATION',
            'REPORT_RESOLVED',
            'REPORT_REJECTED',
            'ITEM_BLOCKED',
            'ITEM_RESTORED',
            'ACCOUNT_SUSPENDED',
            'DISPUTE_OPENED',
            'DISPUTE_RESOLVED',
            'DISPUTE_REJECTED'
        )
    );

create index idx_messages_dispute_id on messages (dispute_id);
