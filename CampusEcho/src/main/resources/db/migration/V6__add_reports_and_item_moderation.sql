alter table items
    add column moderation_status varchar(16) not null default 'NORMAL',
    add column moderation_reason varchar(1000),
    add column moderated_by bigint references users (id) on delete set null,
    add column moderated_at timestamptz,
    add constraint ck_items_moderation_status check (moderation_status in ('NORMAL', 'BLOCKED')),
    add constraint ck_items_moderation_metadata check (
        (moderation_status = 'NORMAL' and (
            (moderation_reason is null and moderated_by is null and moderated_at is null)
            or
            (moderation_reason is not null and moderated_by is not null and moderated_at is not null)
        ))
        or
        (moderation_status = 'BLOCKED'
            and moderation_reason is not null
            and moderated_by is not null
            and moderated_at is not null)
    );

create index idx_items_public_listing
    on items (status, moderation_status, created_at desc);

create table reports (
    id bigint generated by default as identity primary key,
    reporter_id bigint not null references users (id) on delete restrict,
    target_type varchar(16) not null,
    item_id bigint references items (id) on delete restrict,
    reported_user_id bigint references users (id) on delete restrict,
    reason varchar(32) not null,
    description varchar(1000) not null,
    status varchar(16) not null default 'PENDING',
    action varchar(32),
    resolution_note varchar(1000),
    handled_by bigint references users (id) on delete set null,
    handled_at timestamptz,
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    version bigint not null default 0,
    constraint ck_reports_target_type check (target_type in ('ITEM', 'USER')),
    constraint ck_reports_reason check (reason in (
        'FRAUD',
        'PROHIBITED_ITEM',
        'MISLEADING_INFORMATION',
        'HARASSMENT',
        'IMPERSONATION',
        'OTHER'
    )),
    constraint ck_reports_status check (status in ('PENDING', 'RESOLVED', 'REJECTED')),
    constraint ck_reports_action check (action is null or action in (
        'NONE',
        'BLOCK_ITEM',
        'SUSPEND_USER',
        'BLOCK_ITEM_AND_SUSPEND_USER'
    )),
    constraint ck_reports_target check (
        (target_type = 'ITEM' and item_id is not null and reported_user_id is null)
        or
        (target_type = 'USER' and item_id is null and reported_user_id is not null)
    ),
    constraint ck_reports_not_self check (
        reported_user_id is null or reporter_id <> reported_user_id
    ),
    constraint ck_reports_reason_target check (
        (target_type = 'ITEM' and reason in ('FRAUD', 'PROHIBITED_ITEM', 'MISLEADING_INFORMATION', 'OTHER'))
        or
        (target_type = 'USER' and reason in ('FRAUD', 'HARASSMENT', 'IMPERSONATION', 'OTHER'))
    ),
    constraint ck_reports_action_target check (
        action is null
        or target_type = 'ITEM'
        or action in ('NONE', 'SUSPEND_USER')
    ),
    constraint ck_reports_handling check (
        (status = 'PENDING'
            and action is null
            and resolution_note is null
            and handled_by is null
            and handled_at is null)
        or
        (status = 'RESOLVED'
            and action is not null
            and resolution_note is not null
            and handled_by is not null
            and handled_at is not null)
        or
        (status = 'REJECTED'
            and action = 'NONE'
            and resolution_note is not null
            and handled_by is not null
            and handled_at is not null)
    )
);

create unique index uq_reports_pending_item
    on reports (reporter_id, item_id)
    where status = 'PENDING' and target_type = 'ITEM';

create unique index uq_reports_pending_user
    on reports (reporter_id, reported_user_id)
    where status = 'PENDING' and target_type = 'USER';

create index idx_reports_reporter_created_at
    on reports (reporter_id, created_at desc);

create index idx_reports_admin_queue
    on reports (status, target_type, created_at desc);
